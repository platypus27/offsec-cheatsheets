import AxeBuilder from '@axe-core/playwright'
import { expect, test } from '@playwright/test'

test('home offers the field manual and command workspace as direct entry points', async ({ page }) => {
  await page.goto('./')
  const main = page.getByRole('main')
  await main.getByRole('link', { name: /Explore commands/ }).click()
  await expect(page.getByRole('heading', { name: 'Command explorer', exact: true })).toBeVisible()
  await page.goto('./')
  await page
    .getByRole('main')
    .getByRole('link', { name: /Start from your task/ })
    .click()
  await expect(page.getByRole('heading', { name: 'Start from your task', level: 1 })).toBeVisible()
})

test('command explorer combines filters, retains context and opens the exact source', async ({ page }) => {
  await page.goto('./#/tools/commands')
  await expect(page.getByRole('heading', { name: 'Command explorer', exact: true })).toBeVisible()
  await page.getByLabel('Tool', { exact: true }).selectOption('Impacket')
  await page.getByLabel('Service', { exact: true }).selectOption('SMB')
  await page.getByLabel('Find a command').fill('ticket')
  await expect(page.getByRole('status').filter({ hasText: '1 command group' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Find a command')).toHaveValue('ticket')
  await page.getByText('Ticket access', { exact: true }).click()
  await expect(page.getByText('Use this page on Kali with a reviewed ticket cache.')).toBeVisible()
  await expect(
    page.getByText('Run on Kali after obtaining a service ticket.', { exact: false }),
  ).toBeVisible()
  await expect(page.getByRole('region', { name: 'bash code' })).toContainText('impacket-wmiexec')
  await page.getByRole('checkbox', { name: 'Verify ticket principal', exact: true }).check()
  await page.getByRole('link', { name: 'Open full note' }).click()
  await expect(page).toHaveURL(/#\/workflow\/context\?h=ticket-access$/)
  await expect(page.getByRole('heading', { name: 'Ticket access', exact: true })).toBeInViewport()
  const tasks = page.getByRole('checkbox', { name: 'Verify ticket principal', exact: true })
  await expect(tasks.first()).toBeChecked()
  await expect(tasks.last()).not.toBeChecked()
  await page.reload()
  await expect(tasks.first()).toBeChecked()
})

test('command explorer recovers from empty filters and fits a narrow screen', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 780 })
  await page.goto('./#/tools/commands?q=definitely-no-command')
  await expect(page.getByText('No command groups match these filters.')).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByText('SMB shares', { exact: true })).toBeVisible()
  await page.getByText('SMB shares', { exact: true }).click()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
  await page.evaluate(() =>
    Promise.allSettled(document.getAnimations().map((animation) => animation.finished)),
  )
  const results = await new AxeBuilder({ page }).analyze()
  expect(results.violations).toEqual([])
})

test('lab notebook saves per target and exports only the selected machine', async ({ page }) => {
  await page.goto('./#/tools/notebook')
  await expect(page.getByRole('heading', { name: 'Lab notebook', exact: true })).toBeVisible()
  await page.getByLabel('Current status').selectOption('foothold')
  await page.getByLabel('Entry point').fill('SMB configuration exposed a lab credential')
  await page.getByLabel('Next action').fill('Check service permissions on Box 1')
  await page.reload()
  await expect(page.getByLabel('Next action')).toHaveValue('Check service permissions on Box 1')
  await page.getByRole('button', { name: /Edit variables/ }).click()
  await page.getByRole('tab', { name: 'Box 2', exact: true }).click()
  await page.getByRole('button', { name: /Make.*default|Use.*default|Set.*default/i }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Entry point')).toHaveValue('')
  await page.getByLabel('Entry point').fill('Box 2 unique entry')
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export this target' }).click()
  const file = await (await downloaded).path()
  const { readFile } = await import('node:fs/promises')
  const markdown = await readFile(file!, 'utf8')
  expect(markdown).toContain('Box 2 unique entry')
  expect(markdown).not.toContain('lab credential')
  await expect(page.getByLabel('Entry point')).toHaveValue('Box 2 unique entry')
  await page.getByRole('button', { name: /Edit variables/ }).click()
  await page.getByLabel('IP address', { exact: true }).fill('192.0.2.222')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Entry point')).toHaveValue('')
  await page.getByLabel('Entry point').fill('Notes for the new address')
  await page.reload()
  await expect(page.getByLabel('Entry point')).toHaveValue('Notes for the new address')
  await page.getByRole('button', { name: /Edit variables/ }).click()
  await page.getByLabel('IP address', { exact: true }).fill('')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Entry point')).toHaveValue('Box 2 unique entry')
})
